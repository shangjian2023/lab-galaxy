const esc = (s) => s.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
const objects = [];
const pageObjIds = pages.map((_, i) => 4 + i); // 1-based obj ids for pages
const contentObjStart = 4 + pages.length;

pages.forEach((lines, i) => {
  objects[3 + i] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 ${3 + 0} 0 R >> >> /Contents ${contentObjStart + i} 0 R >>`;
});
pages.forEach((lines, i) => {
  const stream = lines.map(([x, y, size, text]) =>
    `BT /F1 ${size} Tf ${x} ${y} Td (${esc(text)}) Tj ET`).join("\n");
  objects[3 + pages.length + i] = `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`;
});
objects[0] = null; // obj 1 catalog (fill below)
objects[1] = null; // obj 2 pages
objects[2] = `<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>`;
objects[0] = `<< /Type /Catalog /Pages 2 0 R >>`;
objects[1] = `<< /Type /Pages /Kids [${pageObjIds.map((id) => `${id} 0 R`).join(" ")}] /Count ${pages.length} >>`;

let pdf = "%PDF-1.4\n";
const offsets = [];
objects.forEach((body, idx) => {
  offsets[idx] = Buffer.byteLength(pdf);
  pdf += `${idx + 1} 0 obj\n${body}\nendobj\n`;
});
const xrefPos = Buffer.byteLength(pdf);
pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
for (let i = 0; i < objects.length; i++) pdf += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefPos}\n%%EOF`;

writeFileSync(out, pdf, "binary");
console.log("OK PDF written:", out, `(${Buffer.byteLength(pdf)} bytes)`);
